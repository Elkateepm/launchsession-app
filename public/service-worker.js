/* LaunchSession service worker.
 * Two jobs:
 *  1. Push notifications (receive + handle clicks) — unchanged from before.
 *  2. Runtime caching of the app shell (HTML/JS/CSS/icons) so the app can
 *     still OPEN when the device has no connection at all. This is separate
 *     from the in-app localStorage caching of register data (children,
 *     session, attendance) — that layer handles "data offline", this layer
 *     handles "the page won't even load offline" (e.g. Safari's
 *     "not connected to the internet" error on a cold load).
 */

const DEFAULT_ICON = '/logo192.png'
const DEFAULT_BADGE = '/favicon.png'
const SHELL_CACHE = 'ls-shell-v1'

self.addEventListener('install', (event) => {
  self.skipWaiting()
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((names) =>
      Promise.all(names.filter((n) => n !== SHELL_CACHE).map((n) => caches.delete(n)))
    ).then(() => self.clients.claim())
  )
})

// ─── APP SHELL RUNTIME CACHING ──────────────────────────────
// No build-time precache manifest here (this file is hand-written, not
// generated by a bundler), so instead we cache opportunistically as the app
// is used: every successful same-origin GET response gets stored, and is
// served from cache when the network is unavailable. In practice this means
// the app becomes fully openable offline after the first normal (online)
// visit — including a fresh Safari launch, not just an already-open tab.
self.addEventListener('fetch', (event) => {
  const { request } = event
  if (request.method !== 'GET') return
  const url = new URL(request.url)
  if (url.origin !== self.location.origin) return // leave Supabase/API calls alone

  // Full-page navigations (e.g. opening/reloading launchsession.co.uk):
  // try the network first for freshness, fall back to the cached shell.
  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request)
        .then((response) => {
          const copy = response.clone()
          caches.open(SHELL_CACHE).then((cache) => cache.put(request, copy))
          return response
        })
        .catch(() =>
          caches.match(request).then((cached) => cached || caches.match('/index.html'))
        )
    )
    return
  }

  // Static assets (JS/CSS/images/icons): cache-first, refresh in the
  // background so the next load picks up any change.
  event.respondWith(
    caches.match(request).then((cached) => {
      const networkFetch = fetch(request)
        .then((response) => {
          if (response && response.ok) {
            const copy = response.clone()
            caches.open(SHELL_CACHE).then((cache) => cache.put(request, copy))
          }
          return response
        })
        .catch(() => cached)
      return cached || networkFetch
    })
  )
})

self.addEventListener('push', (event) => {
  let payload = {}
  try {
    payload = event.data ? event.data.json() : {}
  } catch (e) {
    // Not JSON — fall back to a safe generic notification rather than
    // showing raw/untrusted text.
    payload = {}
  }

  const title = payload.title || 'LaunchSession'
  const body = payload.body || 'You have a new update.'
  const url = payload.url || '/'
  const tag = payload.tag || payload.event_type || undefined

  const options = {
    body,
    icon: payload.icon || DEFAULT_ICON,
    badge: payload.badge || DEFAULT_BADGE,
    tag,
    // Re-notify only for genuinely new events sharing a tag (e.g. don't spam
    // if the same category fires twice quickly), but don't silently merge
    // distinct notifications either.
    renotify: !!tag,
    data: { url, event_type: payload.event_type || null, category: payload.category || null },
    requireInteraction: payload.priority === 'critical',
  }

  event.waitUntil(self.registration.showNotification(title, options))
})

self.addEventListener('notificationclick', (event) => {
  event.notification.close()
  const targetUrl = (event.notification.data && event.notification.data.url) || '/'

  event.waitUntil(
    self.clients.matchAll({ type: 'window', includeUncontrolled: true }).then((clientList) => {
      // Focus an existing LaunchSession tab if one is open, and navigate it.
      for (const client of clientList) {
        try {
          const clientUrl = new URL(client.url)
          if (clientUrl.origin === self.location.origin && 'focus' in client) {
            client.postMessage({ type: 'PUSH_NOTIFICATION_CLICK', url: targetUrl })
            if ('navigate' in client) {
              client.navigate(targetUrl).catch(() => {})
            }
            return client.focus()
          }
        } catch (e) {}
      }
      // No LaunchSession window open — open a new one.
      if (self.clients.openWindow) {
        return self.clients.openWindow(targetUrl)
      }
    })
  )
})

self.addEventListener('notificationclose', (event) => {
  // Reserved for future delivery-analytics (e.g. logging dismissals).
  // Intentionally a no-op for now — nothing sensitive to clean up client-side.
})
